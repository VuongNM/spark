// Draws Spark's pixel logo into resources/icon.svg, then renders resources/icon.png (runtime Dock
// icon) and build/icon.icns (app bundle). Needs rsvg-convert (brew install librsvg).
// The logo is the old five voice bars, rebuilt as lit dots on a 9×9 LED grid.
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

export const GRID = 9
/** Lit dots per column (centred); 0 = an empty column between bars. */
export const BARS = [3, 0, 5, 0, 7, 0, 5, 0, 3]
export const isLit = (col, row) => Math.abs(row - (GRID - 1) / 2) <= (BARS[col] - 1) / 2

const TILE = 824
const ORIGIN = 100
const pitch = (TILE * 0.8) / GRID
const dot = pitch * 0.74
const start = ORIGIN + (TILE - pitch * GRID) / 2 + (pitch - dot) / 2
const rect = (c, r) => `<rect x="${(start + c * pitch).toFixed(1)}" y="${(start + r * pitch).toFixed(1)}" width="${dot.toFixed(1)}" height="${dot.toFixed(1)}" rx="${(dot * 0.26).toFixed(1)}"/>`
const on = []
const off = []
for (let r = 0; r < GRID; r++) for (let c = 0; c < GRID; c++) (isLit(c, r) ? on : off).push(rect(c, r))

// librsvg can't render feDropShadow, so shadows are built from blur + flood + composite.
const shadow = (id, blur, dy, color, opacity) => `
    <filter id="${id}" x="-50%" y="-50%" width="200%" height="200%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="${blur}"/>
      <feOffset dy="${dy}" result="blur"/>
      <feFlood flood-color="${color}" flood-opacity="${opacity}"/>
      <feComposite in2="blur" operator="in"/>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>`

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Generated by scripts/make-icons.mjs; edit BARS there and re-run it. -->
  <defs>
    <linearGradient id="body" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#2a4fa8"/>
      <stop offset="0.55" stop-color="#0f2a6b"/>
      <stop offset="1" stop-color="#06143d"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.28" cy="0.18" r="0.75">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.38"/>
      <stop offset="0.45" stop-color="#ffffff" stop-opacity="0.08"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="warm" cx="0.85" cy="0.95" r="0.6">
      <stop offset="0" stop-color="#ff9e7a" stop-opacity="0.45"/>
      <stop offset="1" stop-color="#ff9e7a" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="led" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="1" stop-color="#e2e8ff"/>
    </linearGradient>${shadow('shadow', 22, 18, '#0a1f52', 0.35)}${shadow('ledglow', 12, 0, '#cfd9ff', 0.6)}
    <clipPath id="tile"><rect x="${ORIGIN}" y="${ORIGIN}" width="${TILE}" height="${TILE}" rx="185"/></clipPath>
  </defs>
  <g filter="url(#shadow)">
    <rect x="${ORIGIN}" y="${ORIGIN}" width="${TILE}" height="${TILE}" rx="185" fill="url(#body)"/>
  </g>
  <g clip-path="url(#tile)">
    <rect x="${ORIGIN}" y="${ORIGIN}" width="${TILE}" height="${TILE}" fill="url(#warm)"/>
    <rect x="${ORIGIN}" y="${ORIGIN}" width="${TILE}" height="${TILE}" fill="url(#glow)"/>
  </g>
  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" fill="none" stroke="#ffffff" stroke-opacity="0.22" stroke-width="3"/>
  <g fill="#ffffff" fill-opacity="0.1">
    ${off.join('\n    ')}
  </g>
  <g fill="url(#led)" filter="url(#ledglow)">
    ${on.join('\n    ')}
  </g>
</svg>
`

if (process.argv[1]?.endsWith('make-icons.mjs')) {
  const root = new URL('..', import.meta.url).pathname
  writeFileSync(join(root, 'resources/icon.svg'), svg)
  const dir = mkdtempSync(join(tmpdir(), 'spark-icons-'))
  const set = join(dir, 'spark.iconset')
  mkdirSync(set)
  const render = (px, out) => execFileSync('rsvg-convert', ['-w', String(px), '-h', String(px), join(root, 'resources/icon.svg'), '-o', out])
  for (const s of [16, 32, 128, 256, 512]) {
    render(s, join(set, `icon_${s}x${s}.png`))
    render(s * 2, join(set, `icon_${s}x${s}@2x.png`))
  }
  copyFileSync(join(set, 'icon_512x512@2x.png'), join(root, 'resources/icon.png'))
  execFileSync('iconutil', ['-c', 'icns', set, '-o', join(root, 'build/icon.icns')])
  rmSync(dir, { recursive: true, force: true })
  console.log('icons updated')
}
